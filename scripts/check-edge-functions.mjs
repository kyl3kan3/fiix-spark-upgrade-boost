import { spawnSync } from "node:child_process";
import { readFile, readdir } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { parse } from "smol-toml";

const root = process.cwd();
const functionsRoot = path.join(root, "supabase", "functions");
const configPath = path.join(root, "supabase", "config.toml");

const mcpViteEmitPath = path.join(
  root,
  "node_modules",
  "@lovable.dev",
  "mcp-js",
  "dist",
  "stacks",
  "supabase",
  "vite.js",
);
try {
  const mcpViteEmit = await readFile(mcpViteEmitPath, "utf8");
  if (!mcpViteEmit.includes("wrapMcpHandler")) {
    throw new Error(
      "@lovable.dev/mcp-js vite emit is missing wrapMcpHandler (patches/@lovable.dev+mcp-js+0.20.1.patch may have failed or the package was upgraded without refreshing the patch). Run: npm ci",
    );
  }
} catch (error) {
  if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
    throw new Error(
      "Missing @lovable.dev/mcp-js — run npm ci before check:edge so the MCP CORS emit patch can apply.",
    );
  }
  throw error;
}

const mcpIndexPath = path.join(functionsRoot, "mcp", "index.ts");
try {
  const mcpIndex = await readFile(mcpIndexPath, "utf8");
  if (!mcpIndex.includes("wrapMcpHandler")) {
    throw new Error(
      "supabase/functions/mcp/index.ts must wrap createSupabaseHandler with wrapMcpHandler (regenerate via npm run build after applying patches).",
    );
  }
} catch (error) {
  if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
    throw new Error("Missing supabase/functions/mcp/index.ts");
  }
  throw error;
}

const config = parse(await readFile(configPath, "utf8"));
const expectedJwtSettings = {
  "authorize-public-request": false,
  "submit-public-request": false,
  "payments-webhook": false,
  "resend-webhook": false,
  "create-checkout-context": true,
  "paddle-portal": true,
  "update-seats": true,
  "meter-readings": false,
  "mcp": false,
};

for (const [functionName, expected] of Object.entries(expectedJwtSettings)) {
  const actual = config.functions?.[functionName]?.verify_jwt;
  if (actual !== expected) {
    throw new Error(
      `${functionName} must set verify_jwt = ${expected}; received ${String(actual)}`,
    );
  }
}

const entries = await readdir(functionsRoot, { withFileTypes: true });
const entrypoints = entries
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_"))
  .map((entry) => path.join("supabase", "functions", entry.name, "index.ts"));

const strictEntrypoints = [];
const generatedEntrypoints = [];
for (const entrypoint of entrypoints) {
  let source;
  try {
    source = await readFile(entrypoint, "utf8");
  } catch {
    // Some function folders contain only shared modules.
    continue;
  }

  if (source.startsWith("// AUTO-GENERATED by @lovable.dev/mcp-js")) {
    if (/npm:[A-Za-z]:[\\\\/]/.test(source)) {
      throw new Error(`${entrypoint} contains a machine-local Windows npm import.`);
    }
    generatedEntrypoints.push(entrypoint);
  } else {
    strictEntrypoints.push(entrypoint);
  }
}

const denoProbe = spawnSync("deno", ["--version"], { stdio: "ignore" });
const useInstalledDeno = denoProbe.status === 0;
const npmCli = process.env.npm_execpath;
if (!useInstalledDeno && !npmCli) {
  throw new Error("Deno is not installed and npm_execpath is unavailable.");
}

function checkEntrypoints(configFile, files) {
  if (files.length === 0) return;

  const command = useInstalledDeno ? "deno" : process.execPath;
  const checkArgs = ["check", "--config", path.join("supabase", "functions", configFile), ...files];
  const args = useInstalledDeno
    ? checkArgs
    : [npmCli, "exec", "--yes", "--", "deno", ...checkArgs];
  const result = spawnSync(command, args, { cwd: root, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

checkEntrypoints("deno.json", strictEntrypoints);
checkEntrypoints("deno.generated.json", generatedEntrypoints);

const edgeTests = [
  path.join("supabase", "functions", "_shared", "cors.test.ts"),
  path.join("supabase", "functions", "mcp", "cors.test.ts"),
  path.join("supabase", "functions", "meter-readings", "handler.test.ts"),
];
const denoConfig = path.join("supabase", "functions", "deno.json");
const testCommand = useInstalledDeno ? "deno" : process.execPath;
const testArgs = ["test", "--config", denoConfig, ...edgeTests];
const testSpawnArgs = useInstalledDeno
  ? testArgs
  : [npmCli, "exec", "--yes", "--", "deno", ...testArgs];
const testResult = spawnSync(testCommand, testSpawnArgs, {
  cwd: root,
  stdio: "inherit",
});
if (testResult.error) throw testResult.error;
if (testResult.status !== 0) process.exit(testResult.status ?? 1);

console.log(
  `Checked ${strictEntrypoints.length} strict and ${generatedEntrypoints.length} generated Edge Function entrypoints, JWT settings, and edge unit tests.`,
);
